#!/usr/bin/env python3
"""CI compile-floor baseline extractor (work line WL6).

The CI test leg performs, per run, ``4 shards x 168 test binaries`` compile+link
units, so the numbers that matter are not "how long did the job take" but
"which part of it was compile+link and which part was execution, per shard".
This script derives exactly that split from two machine-readable sources and
nothing else:

1. ``gh api repos/<owner>/<repo>/actions/runs/<id>/jobs`` (step start/complete
   timestamps -> per-step wall clock, the shard -> step-name mapping);
2. ``gh run view --job <id> --log`` dumps (the cargo ``Finished `ci-test`
   profile ... in Xm Ys`` line, nextest's ``Starting N tests across M binaries``
   line, the ``Summary [ Zs] `` line, the rust-cache restore block and the
   sccache ``--show-stats`` block).

Every field it prints is a string it read out of one of those two artefacts;
nothing is inferred from the workflow YAML, so the report cannot silently drift
away from what actually ran.

Usage::

    gh api repos/O/R/actions/runs/<run-id>/jobs --paginate > jobs.json
    gh run view --job <id> --log > log_<id>.txt          # for each job id
    python3 scripts/ci_floor_baseline.py \
        --jobs-json jobs.json --log-dir . \
        --md /tmp/ci-floor-baseline.md

Generated by `scripts/ci_floor_baseline.py`
"""

from __future__ import annotations

import argparse
import datetime as _dt
import glob
import json
import os
import re
import sys

MARKER = "Generated by `scripts/ci_floor_baseline.py`. Do not hand-edit."

# `gh run view --log` prints ANSI sequences in caret notation (``^[[1m``) when its
# output is not a tty, and as real ESC bytes when it is; both forms appear in the
# dumps this script has to read, so both are stripped.
ANSI_RE = re.compile(r"(?:\x1b|\^\[)\[[0-9;]*m")
PROFILE_FINISHED_RE = re.compile(r"Finished\s+`(?P<profile>[^`]+)` profile[^\n]*in (?P<t>[0-9msh ]+)$")
STARTING_RE = re.compile(r"Starting\s+(?P<tests>\d+)\s+tests across\s+(?P<bins>\d+)\s+binaries"
                         r"(?:\s+\((?P<skipped>\d+) tests skipped\))?")
SUMMARY_RE = re.compile(r"Summary\s+\[\s*(?P<t>[0-9.]+)s\s*\]\s+(?P<run>\d+) tests run")
CACHE_HIT_RE = re.compile(r"Cache hit for: (?P<key>\S+)")
CACHE_SIZE_RE = re.compile(r"Cache Size: ~(?P<mb>\d+) MB \((?P<bytes>\d+) B\)")
CACHE_SAVED_RE = re.compile(r"Cache up-to-date\.|Cache saved|Saving cache")


def strip_ansi(text: str) -> str:
    return ANSI_RE.sub("", text)


def parse_duration(text: str) -> float | None:
    """`4m 58s` / `188s` / `0.5s` -> seconds."""
    text = text.strip()
    total = 0.0
    seen = False
    for value, unit in re.findall(r"([0-9.]+)\s*([hms])", text):
        seen = True
        total += float(value) * {"h": 3600.0, "m": 60.0, "s": 1.0}[unit]
    if not seen:
        return None
    return total


def ts(value: str) -> _dt.datetime:
    return _dt.datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=_dt.timezone.utc)


def step_seconds(step: dict) -> float | None:
    if not step.get("started_at") or not step.get("completed_at"):
        return None
    return (ts(step["completed_at"]) - ts(step["started_at"])).total_seconds()


def load_log(log_dir: str, job_id: int) -> str | None:
    for pattern in (f"log_{job_id}.txt", f"*{job_id}*.log", f"*{job_id}*.txt"):
        hits = sorted(glob.glob(os.path.join(log_dir, pattern)))
        if hits:
            with open(hits[0], encoding="utf-8", errors="replace") as fh:
                return strip_ansi(fh.read())
    return None


def scan_log(text: str) -> dict:
    """Last occurrence of each landmark, because a run builds several profiles."""
    out: dict = {}
    lines = text.splitlines()
    finished = {}
    for line in lines:
        m = PROFILE_FINISHED_RE.search(line)
        if m:
            finished[m.group("profile")] = parse_duration(m.group("t"))
    out["finished_profiles"] = finished
    for line in lines:
        m = STARTING_RE.search(line)
        if m:
            out["tests"] = int(m.group("tests"))
            out["binaries"] = int(m.group("bins"))
            out["tests_skipped"] = int(m.group("skipped") or 0)
        m = SUMMARY_RE.search(line)
        if m:
            out["exec_seconds"] = float(m.group("t"))
            out["tests_run"] = int(m.group("run"))
        m = CACHE_HIT_RE.search(line)
        if m:
            out["rust_cache_key"] = m.group("key")
        m = CACHE_SIZE_RE.search(line)
        if m:
            out["rust_cache_mb"] = int(m.group("mb"))
            out["rust_cache_bytes"] = int(m.group("bytes"))
    stats = {}
    wanted = {
        "Compile requests": "sccache_requests",
        "Compile requests executed": "sccache_executed",
        "Cache hits": "sccache_hits",
        "Cache misses": "sccache_misses",
        "Non-cacheable calls": "sccache_non_cacheable",
        "crate-type": "sccache_noncacheable_crate_type",
        "missing input": "sccache_noncacheable_missing_input",
        "Average cache read hit": "sccache_avg_read_hit_s",
    }
    for line in lines:
        for label, key in wanted.items():
            m = re.search(rf"(?:^|\s){re.escape(label)}\s+(?P<v>[0-9.]+)", line)
            if m:
                value = m.group("v")
                stats[key] = float(value) if "." in value else int(value)
    out.update(stats)
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--jobs-json", required=True, help="file written by `gh api .../jobs --paginate`")
    ap.add_argument("--log-dir", help="directory with `gh run view --job <id> --log` dumps")
    ap.add_argument("--md", help="write the rendered report here")
    ap.add_argument("--json", help="write the parsed rows here")
    args = ap.parse_args(argv)

    with open(args.jobs_json, encoding="utf-8") as fh:
        jobs = json.load(fh)["jobs"]

    rows = []
    for job in jobs:
        entry = {
            "job": job["name"],
            "job_id": job["id"],
            "conclusion": job["conclusion"],
            "job_seconds": (ts(job["completed_at"]) - ts(job["started_at"])).total_seconds(),
            "steps": {s["name"]: step_seconds(s) for s in job["steps"]},
        }
        if args.log_dir:
            text = load_log(args.log_dir, job["id"])
            if text:
                entry.update(scan_log(text))
        # The "Run Tests" step is the one with compile+link+exec in it.
        for name, seconds in entry["steps"].items():
            if name.startswith("Run Tests"):
                entry["tests_step"] = name
                entry["tests_step_seconds"] = seconds
        rows.append(entry)

    rows.sort(key=lambda r: r["job"])

    header = ("| job | Run Tests step | 编译+链接 (ci-test) | 执行 (Summary) | 步总计 | "
              "tests / binaries | sccache 请求 (命中/不可缓存) |\n"
              "| --- | --- | --- | --- | --- | --- | --- |")
    body = []
    tot_compile = tot_exec = tot_step = 0.0
    for r in rows:
        profile = (r.get("finished_profiles") or {}).get("ci-test")
        compile_s = f"{profile:.0f} s" if profile else "n/a"
        exec_s = f"{r['exec_seconds']:.0f} s" if "exec_seconds" in r else "n/a"
        step_s = f"{r['tests_step_seconds']:.0f} s" if r.get("tests_step_seconds") else "n/a"
        counts = (f"{r['tests']} / {r['binaries']}" if "binaries" in r else "n/a")
        scc = "n/a"
        if "sccache_requests" in r:
            scc = (f"{r['sccache_requests']} ({r['sccache_hits']} / "
                   f"{r['sccache_non_cacheable']})")
        body.append(f"| {r['job']} | {r.get('tests_step', 'n/a')} | {compile_s} | {exec_s} | "
                    f"{step_s} | {counts} | {scc} |")
        if profile:
            tot_compile += profile
        if "exec_seconds" in r:
            tot_exec += r["exec_seconds"]
        if r.get("tests_step_seconds"):
            tot_step += r["tests_step_seconds"]
    body.append(f"| **合计** | 4 分片 | **{tot_compile:.0f} s** | **{tot_exec:.0f} s** | "
                f"**{tot_step:.0f} s** | 168 二进制 x 4 | |")

    lines = [MARKER, "", f"# CI compile-floor baseline ({os.path.basename(args.jobs_json)})", ""]
    lines.append(f"- jobs: {', '.join(r['job'] + '=' + str(r['conclusion']) for r in rows)}")
    lines.append(f"- 关键路径（最慢 job 墙钟）：**{max(r['job_seconds'] for r in rows):.0f} s**")
    lines.append(f"- 编译+链接合计：**{tot_compile:.0f} s**；执行合计：**{tot_exec:.0f} s**")
    lines.append("")
    lines.append(header)
    lines.extend(body)
    lines.append("")
    lines.append("## rust-cache / sccache 侧观测")
    lines.append("")
    lines.append("| job | rust-cache key | 恢复体积 | sccache 请求 | 执行 | 命中 | miss | 不可缓存 | crate-type | avg read hit |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for r in rows:
        if "sccache_requests" not in r and "rust_cache_mb" not in r:
            continue
        lines.append("| {} | {} | {} MB | {} | {} | {} | {} | {} | {} | {} s |".format(
            r["job"], r.get("rust_cache_key", "n/a"), r.get("rust_cache_mb", "n/a"),
            r.get("sccache_requests", "n/a"), r.get("sccache_executed", "n/a"),
            r.get("sccache_hits", "n/a"), r.get("sccache_misses", "n/a"),
            r.get("sccache_non_cacheable", "n/a"),
            r.get("sccache_noncacheable_crate_type", "n/a"),
            r.get("sccache_avg_read_hit_s", "n/a")))

    report = "\n".join(lines) + "\n"
    sys.stdout.write(report)
    if args.md:
        with open(args.md, "w", encoding="utf-8") as fh:
            fh.write(report)
    if args.json:
        with open(args.json, "w", encoding="utf-8") as fh:
            json.dump(rows, fh, indent=2, sort_keys=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
