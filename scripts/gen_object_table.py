#!/usr/bin/env python3
"""Emit the object table the C host needs to create instances.

The C reconstruction runs shipped bytecode lowered to C, so it must answer the
same questions `crates/core` answers from `Bundle::objects`:

  * what sprite does object N start with            (id -> sprite)
  * does N have a Create body, and which CODE is it (id -> Create code)
  * if N has none, which ancestors are consulted    (id -> parent_chain)
  * is N persistent across room switches         (id -> persistent)

Nothing here is hand-written: a missing object would otherwise show up as a
silent "sprite 0, no Create" instance instead of an error, which is exactly the
kind of drift the reconstruction is supposed to exclude. The generator therefore
*refuses* (non-zero exit) instead of emitting a partial table:

  * duplicate object ids,
  * a parent chain pointing at an id no object declares,
  * a Create event whose code list is empty,
  * a non-int sprite / parent id.

Object table row order is the shipped id order (ascending). Parent chains are
flattened into one int32 array; each row carries its own (start, count) window
into it, so `dispatch` can walk ancestors without a second lookup table.

    python3 scripts/gen_object_table.py \
        --ir crates/core/src/generated/full_ir.json \
        --out c-recon/gen/objects_data.c
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

MARKER = "Generated by `scripts/gen_object_table.py`"

# Event codes: type 0 = Create, subtype 0 = the plain Create event.
EV_CREATE = 0
EV_CREATE_SUB = 0


def load_objects(ir_path: Path):
    ir = json.loads(ir_path.read_text())
    if "objects" not in ir:
        raise SystemExit(f"{ir_path}: no objects[] array")
    objs = ir["objects"]
    if not objs:
        raise SystemExit(f"{ir_path}: objects[] is empty")
    return ir, objs


def load_asset_strings(asset_path: Path) -> list[str]:
    """Read STRG directly; generated full_ir snapshots may omit this table."""
    from reverse_code import Reader

    reader = Reader(asset_path.read_bytes())
    lo, hi = reader.chunks["STRG"]
    strings = []
    for pos in reader.table(lo, lo, hi):
        size = reader.u32(pos)
        raw = reader.data[pos + 4:pos + 4 + size]
        if b"\0" in raw:
            raise SystemExit(f"{asset_path}: embedded NUL in STRG entry {len(strings)}")
        strings.append(raw.decode("utf-8", errors="replace"))
    return strings


def as_id(value, what: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool):
        raise SystemExit(f"{what}: expected an integer id, got {value!r}")
    return value


def create_code(obj: dict) -> int:
    for ev in obj["events"]:
        if ev["event_type"] == EV_CREATE and ev["subtype"] == EV_CREATE_SUB:
            codes = ev["codes"]
            if not codes:
                raise SystemExit(f"object {obj['id']} ({obj['name']}): Create event with no codes")
            return as_id(codes[0], f"object {obj['id']} Create code")
    return -1


def build(ir_path: Path):
    ir, objs = load_objects(ir_path)
    known = {as_id(o["id"], "object id") for o in objs}
    if len(known) != len(objs):
        raise SystemExit(f"{ir_path}: duplicate object ids")

    rows = []
    parents: list[int] = []
    events: list[tuple[int, int, int, int]] = []
    for obj in sorted(objs, key=lambda o: o["id"]):
        oid = as_id(obj["id"], "object id")
        sprite = as_id(obj["sprite"], f"object {oid} sprite")
        chain = [as_id(p, f"object {oid} parent") for p in obj["parent_chain"]]
        for p in chain:
            if p not in known:
                raise SystemExit(f"object {oid} ({obj['name']}): parent {p} is not a declared object")
        rows.append(
            {
                "id": oid,
                "name": obj["name"],
                "sprite": sprite,
                "depth": as_id(obj["depth"], f"object {oid} depth"),
                "create": create_code(obj),
                "persistent": 1 if obj.get("persistent") else 0,
                "start": len(parents),
                "count": len(chain),
            }
        )
        parents.extend(chain)
        for ev in obj["events"]:
            etype = as_id(ev["event_type"], f"object {oid} event_type")
            sub = as_id(ev["subtype"], f"object {oid} subtype")
            for c in ev["codes"]:
                events.append((oid, etype, sub, as_id(c, f"object {oid} code")))
    return ir, rows, parents, events


def emit(ir_path: Path, ir: dict, rows, parents, events) -> str:
    n = len(rows)
    string_rows = []
    string_data = bytearray()
    for text in ir.get("string_table") or []:
        raw = text.encode("utf-8")
        string_rows.append((len(string_data), len(raw)))
        string_data.extend(raw)
        string_data.append(0)
    out: list[str] = []
    w = out.append
    w(f"/* {MARKER} from {ir_path.as_posix()}; do not hand-edit. */")
    w("/*")
    w(" * Object table for the C host: one row per shipped object, in id order.")
    w(" *")
    w(f" * source_sha256 {ir.get('source_sha256', '(absent)')}")
    w(" *")
    w(" * create_code is the first code of event (type 0, subtype 0), or -1 when")
    w(" * the object has no Create body of its own. parent_start/parent_count")
    w(" * window into GM_OBJECT_PARENTS, the flattened parent_chain used by")
    w(" * dispatch's inherited-event fallback (ir_scene.rs dispatch()).")
    w(" */")
    w('#include "gml.h"')
    w("")
    w("typedef struct {")
    w("    int32_t id;")
    w("    int32_t sprite;")
    w("    int32_t depth;")
    w("    int32_t create_code;   /* -1: no Create event of its own */")
    w("    int32_t persistent;    /* GM room-switch retention flag */")
    w("    int32_t parent_start;  /* offset into GM_OBJECT_PARENTS */")
    w("    int32_t parent_count;")
    w("    const char* name;")
    w("} GmObjectRow;")
    w("")
    w(f"const int GM_OBJECT_COUNT = {n};")
    w(f"const int GM_OBJECT_PARENT_EDGES = {len(parents)};")
    w("")
    w("static const int32_t GM_OBJECT_PARENTS[] = {")
    if parents:
        for i in range(0, len(parents), 12):
            w("    " + ", ".join(str(p) for p in parents[i : i + 12]) + ",")
    else:
        w("    0 /* unused: no object declares a parent */")
    w("};")
    w("")
    w("/* (object, event_type, subtype) -> code, in object order. */")
    w("static const GmEventRow GM_EVENTS[] = {")
    if events:
        for (o, t, s, c) in events:
            w(f"    {{ {o}, {t}, {s}, {c} }},")
    else:
        w("    { -1, -1, -1, -1 },")
    w("};")
    w(f"const int GM_EVENT_COUNT = {len(events)};")
    w(f"const int GM_STRING_TABLE_LEN = {len(string_rows)};")
    w("typedef struct { uint32_t offset, length; } GmStringRow;")
    w("static const GmStringRow GM_STRING_ROWS[] = {")
    if string_rows:
        for offset, length in string_rows:
            w(f"    {{ {offset}, {length} }},")
    else:
        w("    { 0, 0 },")
    w("};")
    w("static const unsigned char GM_STRING_DATA[] = {")
    if string_data:
        for i in range(0, len(string_data), 16):
            w("    " + ", ".join(str(b) for b in string_data[i:i + 16]) + ",")
    else:
        w("    0,")
    w("};")
    w("const char* gm_static_string(int32_t index) {")
    w("    return (index >= 0 && index < GM_STRING_TABLE_LEN)")
    w("        ? (const char*)GM_STRING_DATA + GM_STRING_ROWS[index].offset : NULL;")
    w("}")
    w("")
    w("int gm_event_code(int32_t object, int32_t type, int32_t subtype) {")
    w("    for (int i = 0; i < GM_EVENT_COUNT; i++)")
    w("        if (GM_EVENTS[i].object == object && GM_EVENTS[i].type == type &&")
    w("            GM_EVENTS[i].subtype == subtype) return GM_EVENTS[i].code;")
    w("    return -1;")
    w("}")
    w("")
    w("/* dispatch(): own event first, then the first ancestor carrying one. */")
    w("int gm_event_code_chain(int32_t object, int32_t type, int32_t subtype) {")
    w("    int c = gm_event_code(object, type, subtype);")
    w("    if (c >= 0) return c;")
    w("    int n = gm_object_parent_count(object);")
    w("    for (int k = 0; k < n; k++) {")
    w("        c = gm_event_code(gm_object_parent(object, k), type, subtype);")
    w("        if (c >= 0) return c;")
    w("    }")
    w("    return -1;")
    w("}")
    w("")
    w("static const GmObjectRow GM_OBJECTS[] = {")
    for r in rows:
        w(
            f'    {{ {r["id"]}, {r["sprite"]}, {r["depth"]}, {r["create"]}, {r["persistent"]}, '
            f'{r["start"]}, {r["count"]}, "{r["name"]}" }},'
        )
    w("};")
    w("")
    w("/* ids are sorted ascending, so a binary search is the whole lookup. */")
    w("static int obj_index(int32_t id) {")
    w("    int lo = 0, hi = GM_OBJECT_COUNT - 1;")
    w("    while (lo <= hi) {")
    w("        int mid = lo + (hi - lo) / 2;")
    w("        int32_t k = GM_OBJECTS[mid].id;")
    w("        if (k == id) return mid;")
    w("        if (k < id) lo = mid + 1; else hi = mid - 1;")
    w("    }")
    w("    return -1;")
    w("}")
    w("")
    w("int gm_object_exists(int32_t id) { return obj_index(id) >= 0; }")
    w("")
    w("/* The collision parent graph needs every declared object, not just the ones")
    w(" * the fixture happens to place, so expose the id roster. */")
    w("int32_t gm_object_id_at(int index) {")
    w("    return (index >= 0 && index < GM_OBJECT_COUNT) ? GM_OBJECTS[index].id : -1;")
    w("}")
    w("")
    w("const char* gm_object_name(int32_t id) {")
    w("    int i = obj_index(id);")
    w("    return i >= 0 ? GM_OBJECTS[i].name : NULL;")
    w("}")
    w("")
    w("int32_t gm_object_sprite(int32_t id) {")
    w("    int i = obj_index(id);")
    w("    return i >= 0 ? GM_OBJECTS[i].sprite : -1;")
    w("}")
    w("")
    w("double gm_object_depth(int32_t id) {")
    w("    int i = obj_index(id);")
    w("    return i >= 0 ? (double)GM_OBJECTS[i].depth : 0.0;")
    w("}")
    w("")
    w("/* -1 covers both \"no Create body\" and \"unknown object\"; pair with")
    w(" * gm_object_exists() when the difference matters. */")
    w("int gm_object_create_code(int32_t id) {")
    w("    int i = obj_index(id);")
    w("    return i >= 0 ? GM_OBJECTS[i].create_code : -1;")
    w("}")
    w("")
    w("int gm_object_persistent(int32_t id) {")
    w("    int i = obj_index(id);")
    w("    return i >= 0 ? GM_OBJECTS[i].persistent : 0;")
    w("}")
    w("")
    w("int gm_object_parent_count(int32_t id) {")
    w("    int i = obj_index(id);")
    w("    return i >= 0 ? GM_OBJECTS[i].parent_count : 0;")
    w("}")
    w("")
    w("int32_t gm_object_parent(int32_t id, int index) {")
    w("    int i = obj_index(id);")
    w("    if (i < 0 || index < 0 || index >= GM_OBJECTS[i].parent_count) return -1;")
    w("    return GM_OBJECT_PARENTS[GM_OBJECTS[i].parent_start + index];")
    w("}")
    w("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ir", type=Path, default=Path("crates/core/src/generated/full_ir.json"))
    ap.add_argument("--asset", type=Path, default=Path("assets/game.droid"))
    ap.add_argument("--out", type=Path, default=Path("c-recon/gen/objects_data.c"))
    a = ap.parse_args()
    ir, rows, parents, events = build(a.ir)
    ir["string_table"] = load_asset_strings(a.asset)
    print(f"strings: {len(ir['string_table'])} entries <- {a.asset}")
    a.out.write_text(emit(a.ir, ir, rows, parents, events))
    by_id = {r["id"]: r for r in rows}
    with_create = sum(1 for r in rows if r["create"] >= 0)
    inherited = 0
    for r in rows:
        if r["create"] >= 0 or r["count"] == 0:
            continue
        # Mirror dispatch(): first ancestor that carries the event wins.
        for k in range(r["count"]):
            p = by_id[parents[r["start"] + k]]
            if p["create"] >= 0:
                inherited += 1
                break
    print(
        f"objects: {len(rows)} rows ({with_create} with Create, "
        f"{len(rows) - with_create} without, {inherited} inheriting one from a parent) "
        f"-> {a.out}"
    )
    print(f"parent edges: {len(parents)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
