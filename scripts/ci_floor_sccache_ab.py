#!/usr/bin/env python3
"""sccache wrapper A/B on this project's real ci-test units (work line WL6/WL11).

What this measures, and why it is measurable at all:

The CI leg runs each test unit through ``RUSTC_WRAPPER=sccache`` even though
sccache refuses to cache the units that dominate the leg. Its own stats block
says so: ``192`` of ``198`` requests per shard are ``Non-cacheable calls``, and
``crate-type`` is the reason for ``188`` of them. So the honest question is not
"how much does sccache save" but "what does the wrapper cost on the requests it
cannot serve, versus the ~6 reads it does serve".

This script answers it on real units instead of on a synthetic crate:

1. ``cargo test --no-run --profile ci-test -p <pkg> -v`` is run once with a
   ``RUSTC_WRAPPER`` probe installed, so the exact ``rustc`` command line *and
   the exact environment* cargo used for a chosen test unit are captured (the
   probe records ``argv`` + ``env`` and then execs the real compiler).
2. The captured unit is then executed directly, in alternating rounds:

   * arm ``bare``   - the command as cargo ran it;
   * arm ``sccache``- the same command prefixed with the ``sccache`` binary,
     which is what ``RUSTC_WRAPPER=sccache`` makes cargo do.

   Running rustc directly (rather than through cargo) is what makes the two arms
   comparable: cargo would skip a ``fresh`` unit, so a wrapper-vs-no-wrapper
   wall-clock comparison through cargo measures freshness bookkeeping, not the
   wrapper.
3. For every run the script records wall clock, child CPU time, the current
   load average, and the digest of the artifacts the run wrote. The digest is the
   equivalence check: both arms must produce byte-identical output or the
   measurement is reported but flagged as not comparable.
4. ``sccache --show-stats --stats-format=json`` is sampled around the runs, so
   the report can attribute each wrapped run to hit / miss / non-cacheable
   instead of assuming it.

Why the env capture exists (WL11 fix, 2026-10-16): the first version of this
script replayed only the command line, and every runnable unit in this tree dies
immediately under a bare replay with

    error: environment variable `CARGO_MANIFEST_DIR` not defined at compile time

(this project's IR tests do ``env!("CARGO_MANIFEST_DIR")`` to locate the repo
root). Cargo sets that variable per unit at compile time, and it is not in the
shell environment, so a direct replay without it measures a failing compile --
six identical ~1 s non-runs -- rather than the wrapper. The unit environment is
therefore captured from the real cargo invocation through the same
``RUSTC_WRAPPER`` hook cargo itself uses. The capture run is the *only* place a
wrapper is used, and it is excluded from the measured arms.

Usage::

    python3 scripts/ci_floor_sccache_ab.py --pkg callys-core \\
        --test sprite_and_tile_layout_ir --rounds 3 --json out.json
    python3 scripts/ci_floor_sccache_ab.py --pkg callys-core \\
        --unit-mode lib --rounds 3 --json out_lib.json

Generated by `scripts/ci_floor_sccache_ab.py`
"""

from __future__ import annotations

import argparse
import glob
import hashlib
import json
import os
import re
import resource
import shlex
import shutil
import statistics
import subprocess
import sys
import tempfile
import time

MARKER = "Generated by `scripts/ci_floor_sccache_ab.py`. Do not hand-edit."

# Installed as RUSTC_WRAPPER only for the capture step: it records the argv and
# the environment of each compiler invocation, then execs the real compiler so
# the capture build still succeeds. Framing is
# `<argv entry>\\0 ... \\0 \\0 <KEY=VALUE>\\0 ...`, which parses unambiguously.
#
# It is Python rather than a shell one-liner because the shebang has to resolve
# on both CI (x86_64 Ubuntu) and Termux/aarch64, where ``/usr/bin/env`` does not
# exist; ``{python}`` is the running interpreter, which is by construction the
# one that can run this file.
PROBE_SCRIPT = '''#!{python}
# argv+env capture probe (RUSTC_WRAPPER), generated by ci_floor_sccache_ab.py.
import os
import sys
import tempfile

fd, out = tempfile.mkstemp(prefix="rec.", dir=os.environ["PROBE_DIR"])
with os.fdopen(fd, "wb") as fh:
    for arg in sys.argv[1:]:
        fh.write(arg.encode() + b"\\0")
    fh.write(b"\\0")
    for key, value in os.environ.items():
        fh.write(f"{{key}}={{value}}".encode() + b"\\0")
os.execvp(sys.argv[1], sys.argv[1:])
'''


def log(msg: str) -> None:
    sys.stderr.write(msg + "\n")
    sys.stderr.flush()


def loadavg() -> str:
    """1-minute load average.

    Android/Termux hides ``/proc/loadavg`` from the app uid (EACCES) and Python
    built for Android has no ``os.getloadavg``, so the value is taken from
    ``uptime`` and the source of every failure mode is reported verbatim instead
    of being papered over with a 0.
    """
    try:
        with open("/proc/loadavg") as fh:
            return fh.read().split()[0]
    except OSError:
        pass
    try:
        proc = subprocess.run(["uptime"], capture_output=True, text=True)
        m = re.search(r"load average[s]?:\s*([0-9.]+)", proc.stdout)
        if m:
            return m.group(1)
        return f"unparsed({proc.stdout.strip()[-40:]})"
    except OSError as exc:
        return f"unavailable({exc})"


def parse_probe_records(probe_dir: str) -> list[dict]:
    """Read every argv+env record the probe wrote (order is not meaningful)."""
    records = []
    for path in sorted(glob.glob(os.path.join(probe_dir, "rec.*"))):
        with open(path, "rb") as fh:
            blob = fh.read()
        parts = blob.split(b"\0")
        try:
            sep = parts.index(b"")
        except ValueError:
            continue
        argv = [p.decode(errors="replace") for p in parts[:sep]]
        env = {}
        for entry in parts[sep + 1:]:
            if not entry:
                continue
            key, _, value = entry.decode(errors="replace").partition("=")
            if key:
                env[key] = value
        if argv:
            records.append({"argv": argv, "env": env})
    return records


def expected_crate_name(pkg: str, test: str | None, unit_mode: str) -> str:
    """Crate name cargo passes in ``--crate-name`` for the unit we want."""
    if unit_mode == "test" and test:
        return test.replace("-", "_")
    return pkg.replace("-", "_")


def capture_unit(workdir: str, pkg: str, test: str | None, profile: str,
                 extra: list[str], sources: list[str], unit_mode: str) -> tuple[list[str], dict]:
    """Ask cargo to build the unit and keep the `rustc` argv *and* env it used.

    Cargo only builds units it decides to build, so the unit's sources are
    touched first - otherwise a warm target directory makes the capture step a
    no-op and there is nothing to capture.

    ``unit_mode`` picks which of the recorded units to keep: ``test`` (a
    ``--test`` harness binary, the sccache non-cacheable majority) or ``lib`` (an
    rlib, the only crate type sccache will cache).

    Returns ``(argv, env)`` of the chosen unit, both taken from the probe (i.e.
    from what cargo really ran), never reconstructed from the shell.
    """
    for src in sources:
        path = src if os.path.isabs(src) else os.path.join(workdir, src)
        if not os.path.exists(path):
            raise SystemExit(f"--source {path} does not exist")
        os.utime(path, None)
        log(f"[capture] touched {path}")
    if unit_mode == "test":
        cmd = ["cargo", "test", "--no-run", "--profile", profile, "-p", pkg, "-v", *extra]
    else:
        cmd = ["cargo", "build", "--profile", profile, "-p", pkg, "-v", *extra]
    if test:
        cmd += ["--test", test]

    probe_dir = tempfile.mkdtemp(prefix="ci-floor-ab-probe-")
    try:
        probe = os.path.join(probe_dir, "probe.py")
        with open(probe, "w", encoding="utf-8") as fh:
            fh.write(PROBE_SCRIPT.format(python=sys.executable))
        os.chmod(probe, 0o755)
        env = dict(os.environ)
        env["RUSTC_WRAPPER"] = probe
        env["PROBE_DIR"] = probe_dir
        log(f"[capture] {' '.join(shlex.quote(c) for c in cmd)}  [RUSTC_WRAPPER=probe]")
        proc = subprocess.run(cmd, cwd=workdir, capture_output=True, text=True, env=env)
        if proc.returncode != 0:
            log(proc.stdout[-4000:])
            log(proc.stderr[-4000:])
            raise SystemExit(f"cargo exited {proc.returncode}; cannot capture a unit")
        records = parse_probe_records(probe_dir)
    finally:
        shutil.rmtree(probe_dir, ignore_errors=True)

    compiled = [r for r in records if "--crate-name" in r["argv"]]
    if not compiled:
        raise SystemExit("the capture run recorded no compiler invocation")
    name = expected_crate_name(pkg, test, unit_mode)
    named = [r for r in compiled if r["argv"][r["argv"].index("--crate-name") + 1] == name]
    pool = named or compiled
    if unit_mode == "test":
        pool = [r for r in pool if "--test" in r["argv"]]
    else:
        pool = [r for r in pool if "--test" not in r["argv"]]
    if not pool:
        raise SystemExit(f"no recorded `rustc` invocation for unit_mode={unit_mode} "
                         f"(crate-name {name}); recorded: "
                         f"{sorted({r['argv'][r['argv'].index('--crate-name') + 1] for r in compiled})}")
    chosen = pool[-1]  # last unit cargo built
    return chosen["argv"], chosen["env"]


def artifact_digest(out_dir: str, since: float) -> tuple[str, list[str]]:
    """Digest of every file under out_dir written after `since` (the run window)."""
    digests = []
    names = []
    for path in sorted(glob.glob(os.path.join(out_dir, "*"))):
        try:
            st = os.stat(path)
        except OSError:
            continue
        if st.st_mtime >= since - 1.0 and st.st_size > 0:
            h = hashlib.sha256()
            with open(path, "rb") as fh:
                for chunk in iter(lambda: fh.read(1 << 20), b""):
                    h.update(chunk)
            digests.append((os.path.basename(path), h.hexdigest(), st.st_size))
            names.append(os.path.basename(path))
    blob = json.dumps(sorted(digests), sort_keys=True).encode()
    return hashlib.sha256(blob).hexdigest()[:16], names


def out_dir_of(cmd: list[str]) -> str:
    for i, arg in enumerate(cmd):
        if arg == "--out-dir":
            return cmd[i + 1]
        if arg.startswith("--out-dir="):
            return arg.split("=", 1)[1]
    raise SystemExit("captured rustc command has no --out-dir")


def run_once(argv: list[str], workdir: str, env: dict) -> dict:
    """Run argv, return wall seconds, child CPU seconds, exit code and output tail."""
    before = resource.getrusage(resource.RUSAGE_CHILDREN)
    t0 = time.monotonic()
    proc = subprocess.run(argv, cwd=workdir, capture_output=True, text=True, env=env)
    wall = time.monotonic() - t0
    after = resource.getrusage(resource.RUSAGE_CHILDREN)
    cpu = (after.ru_utime - before.ru_utime) + (after.ru_stime - before.ru_stime)
    return {
        "wall_s": wall,
        "cpu_s": cpu,
        "exit": proc.returncode,
        "stderr_tail": proc.stderr[-400:],
    }


def sccache_stats() -> dict:
    if not shutil.which("sccache"):
        return {}
    proc = subprocess.run(["sccache", "--show-stats", "--stats-format=json"],
                          capture_output=True, text=True)
    if proc.returncode != 0:
        return {}
    try:
        return json.loads(proc.stdout).get("stats", {})
    except json.JSONDecodeError:
        return {}


def flatten_stats(stats: dict) -> dict:
    """Collapse sccache 0.18's nested JSON counters into scalars.

    ``cache_hits`` / ``cache_misses`` come back as ``{"counts": {"Rust": N},
    "adv_counts": {...}}``, so a naive ``stats[key]`` is a dict and any
    arithmetic on it either explodes or (worse) gets silently dropped by an
    isinstance guard - which is how the first version of this script managed to
    report every run without ever attributing a hit or a miss.
    """
    out = {}
    for key, value in stats.items():
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            out[key] = value
        elif isinstance(value, dict):
            counts = value.get("counts")
            if isinstance(counts, dict) and counts and \
                    all(isinstance(v, (int, float)) for v in counts.values()):
                out[key] = sum(counts.values())
    return out


def delta_stats(before: dict, after: dict, keys: list[str]) -> dict:
    raw_before, raw_after = before, after
    flat_before, flat_after = flatten_stats(before), flatten_stats(after)
    out = {}
    for key in keys:
        b, a = flat_before.get(key, 0), flat_after.get(key, 0)
        if isinstance(a, (int, float)) and isinstance(b, (int, float)):
            out[key] = a - b
    # `not_cached` is the reason breakdown sccache prints as
    # "Non-cacheable reasons:" in its human-readable stats (the same field the CI
    # post-step reports as `crate-type 188`). It is a plain dict of counters with
    # no `counts` sub-object, so it is read from the *raw* stats - flatten_stats
    # deliberately drops it.
    for reason in sorted(set(raw_after.get("not_cached", {})) | set(raw_before.get("not_cached", {}))):
        b = raw_before.get("not_cached", {}).get(reason, 0)
        a = raw_after.get("not_cached", {}).get(reason, 0)
        out[f"not_cached[{reason}]"] = a - b
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--workdir", default=".", help="workspace root")
    ap.add_argument("--pkg", required=True)
    ap.add_argument("--test", help="test target name (integration test file stem)")
    ap.add_argument("--profile", default="ci-test")
    ap.add_argument("--rounds", type=int, default=3, help="rounds per arm (A/B alternate)")
    ap.add_argument("--extra", nargs="*", default=[], help="extra cargo args for the capture step")
    ap.add_argument("--source", action="append", default=[],
                    help="source file to touch before the capture step (repeatable); "
                         "the unit's own crate root or test file")
    ap.add_argument("--no-warmup", action="store_true",
                    help="skip the discarded warm-up invocation (keeps the sccache "
                         "server-start cost in round 0)")
    ap.add_argument("--unit-mode", choices=("test", "lib"), default="test",
                    help="which unit to capture: a --test harness binary (default) "
                         "or an rlib")
    ap.add_argument("--json", help="write the raw rows here")
    args = ap.parse_args(argv)

    workdir = os.path.abspath(args.workdir)
    sccache_bin = shutil.which("sccache")
    if not sccache_bin:
        raise SystemExit("sccache not on PATH; install it before measuring the wrapper")

    cmd, env = capture_unit(workdir, args.pkg, args.test, args.profile, args.extra,
                            args.source, args.unit_mode)
    crate_name = cmd[cmd.index("--crate-name") + 1]
    out_dir = out_dir_of(cmd)
    # The probe runs as RUSTC_WRAPPER, so its own variable must not leak into the
    # measured arms: the only difference between them is the leading sccache.
    env.pop("RUSTC_WRAPPER", None)
    log(f"[capture] unit: {crate_name}  out-dir: {out_dir}")
    log(f"[capture] command has {len(cmd)} argv entries; "
        f"env replayed: {len(env)} vars (from the cargo invocation)")

    keys = ["compile_requests", "requests_executed", "requests_not_cacheable",
            "cache_hits", "cache_misses", "cache_writes", "compilations",
            "requests_unsupported_compiler", "requests_not_compile"]
    # Warm-up: the first invocation of the sccache client starts its server (and
    # on a cold local cache may do a cache write!), which costs seconds and would
    # otherwise be charged to whichever arm happens to run first.
    if not args.no_warmup:
        log("[warmup] one wrapped invocation, discarded")
        run_once([sccache_bin] + cmd, workdir, env)

    rows = []
    for round_index in range(args.rounds):
        order = ["bare", "sccache"] if round_index % 2 == 0 else ["sccache", "bare"]
        for arm in order:
            before = sccache_stats()
            stamp = time.time()
            argv_run = cmd if arm == "bare" else [sccache_bin] + cmd
            row = run_once(argv_run, workdir, env)
            row["artifact_digest"], row["artifacts"] = artifact_digest(out_dir, stamp)
            row["round"] = round_index
            row["arm"] = arm
            row["loadavg"] = loadavg()
            row["sccache_delta"] = delta_stats(before, sccache_stats(), keys)
            rows.append(row)
            log(f"[run] round={round_index} arm={arm:7s} wall={row['wall_s']:7.3f}s "
                f"cpu={row['cpu_s']:7.3f}s load={row['loadavg']} exit={row['exit']} "
                f"artifact={row['artifact_digest']}")

    summary = {}
    for arm in ("bare", "sccache"):
        walls = [r["wall_s"] for r in rows if r["arm"] == arm]
        cpus = [r["cpu_s"] for r in rows if r["arm"] == arm]
        summary[arm] = {
            "n": len(walls),
            "wall_min": min(walls),
            "wall_median": statistics.median(walls),
            "cpu_min": min(cpus),
            "cpu_median": statistics.median(cpus),
        }
    digests = {arm: sorted({r["artifact_digest"] for r in rows if r["arm"] == arm})
               for arm in ("bare", "sccache")}
    equivalent = digests["bare"] == digests["sccache"] and len(digests["bare"]) == 1
    all_ok = all(r["exit"] == 0 for r in rows)
    delta_min = summary["sccache"]["wall_min"] - summary["bare"]["wall_min"]
    delta_median = summary["sccache"]["wall_median"] - summary["bare"]["wall_median"]

    report = [
        MARKER,
        "",
        f"# sccache wrapper A/B — unit `{crate_name}` "
        f"({args.pkg}, cargo profile `{args.profile}`, unit-mode `{args.unit_mode}`)",
        "",
        f"- rounds per arm: {args.rounds} (A/B alternating order), loadavg printed per run",
        f"- captured command: {len(cmd)} argv entries, env replayed from the cargo "
        f"invocation ({len(env)} vars)",
        f"- all runs exited 0: **{all_ok}**",
        f"- bare    : {summary['bare']['wall_min']:.3f} s min / {summary['bare']['wall_median']:.3f} s median "
        f"(CPU {summary['bare']['cpu_min']:.3f} / {summary['bare']['cpu_median']:.3f} s)",
        f"- sccache : {summary['sccache']['wall_min']:.3f} s min / {summary['sccache']['wall_median']:.3f} s median "
        f"(CPU {summary['sccache']['cpu_min']:.3f} / {summary['sccache']['cpu_median']:.3f} s)",
        f"- delta (sccache - bare): **{delta_min:+.3f} s min**, {delta_median:+.3f} s median",
        f"- artifact equivalence: **{'identical' if equivalent else 'NOT identical'}** "
        f"(digests bare={digests['bare']}, sccache={digests['sccache']})",
        "",
        "| round | arm | wall s | CPU s | loadavg | exit | artifact digest | sccache delta |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        report.append(f"| {row['round']} | {row['arm']} | {row['wall_s']:.3f} | {row['cpu_s']:.3f} | "
                      f"{row['loadavg']} | {row['exit']} | {row['artifact_digest']} | "
                      f"{json.dumps(row['sccache_delta'], sort_keys=True)} |")
    report.append("")
    text = "\n".join(report) + "\n"
    sys.stdout.write(text)
    if args.json:
        with open(args.json, "w", encoding="utf-8") as fh:
            json.dump({"command": cmd, "rows": rows, "summary": summary,
                       "equivalent": equivalent, "all_exit_zero": all_ok,
                       "env_vars_replayed": sorted(env)}, fh, indent=2, sort_keys=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
