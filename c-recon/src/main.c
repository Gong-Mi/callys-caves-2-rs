/* State dump / differential driver.
 *
 * Reads a line-oriented state file, runs one lowered CODE function, writes the
 * resulting state in the same format. The Rust side
 * (crates/core/examples/ir_state_dump.rs) speaks the same protocol, so the two
 * implementations can be diffed byte for byte:
 *
 *     CODE    <id>
 *     CURRENT <instance id>
 *     OTHER   <collision other id>
 *     INST    <id> <object> [alive [active]]
 *     FIELD   <instance id> <name> <value>
 *     ARRAY   <instance id> <name> <index> <value>
 *     GLOBAL  <name> <value>
 *     ROOM    <room id>            (fixture setup and dump)
 *     WARP    <room id>            (seed a pending warp)
 *     WARP                         (consume it at the client boundary)
 *     VIEW    <index> <visible> <x> <y> <w> <h>
 *     DRAW    <view>               (run normal Draw + Draw GUI passes)
 *
 * The two trailing INST tokens are optional and default to 1, because `with` and
 * the scheduler distinguish alive (retired by instance_destroy) from active
 * (parked by instance_deactivate_*). A dump prints `ACTIVE <id> 0` for a
 * deactivated instance, and nothing extra for a live one. `ACTIVE` is dump-only;
 * fixture input expresses deactivation with the fourth INST token.
 */
#include "gml.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>

void gml_0012(GmVM* vm);
void gml_0792(GmVM* vm);
void gm_objects_reset(void);   /* fresh-Scene hook: ids and audio voices restart */
int  gml_dispatch(GmVM* vm, long code);   /* generated by scripts/gen_registry.py */

static int run_code(GmVM* vm, long code, int32_t self) {
    vm->cur = self;
    if (gml_dispatch(vm, code)) return 1;
    fprintf(stderr, "no generated function for CODE %ld\n", code);
    return 0;
}

/* Rust's f64 Display: the shortest decimal that round-trips, written in plain
 * positional notation (never scientific). %.Ng yields the shortest form but
 * switches to exponent notation below 1e-4, so a plain form is searched first
 * and the exponent form is only a fallback for magnitudes a positional string
 * cannot hold in the buffer. */
static void fmt_num(char* buf, size_t n, double v) {
    gm_fmt_num(buf, n, v);
}

static int cmp_field(const void* a, const void* b) {
    return strcmp(((const GmField*)a)->name, ((const GmField*)b)->name);
}
static int cmp_slot(const void* a, const void* b) {
    const GmArraySlot* x = a; const GmArraySlot* y = b;
    int c = strcmp(x->name, y->name);
    return c ? c : (x->index - y->index);
}
static int cmp_global(const void* a, const void* b) {
    return strcmp(((const GmGlobal*)a)->name, ((const GmGlobal*)b)->name);
}

static void dump(FILE* f, GmVM* vm) {
    char b1[512], b2[512];
    fmt_num(b1, sizeof b1, vm->current_room);
    fprintf(f, "ROOM %s\n", b1);
    fmt_num(b1, sizeof b1, vm->room_width); fmt_num(b2, sizeof b2, vm->room_height);
    fprintf(f, "ROOMW %s\nROOMH %s\n", b1, b2);
    if (vm->has_room_warp) fprintf(f, "WARP %llu\n", (unsigned long long)vm->target_room_warp);
    if (vm->other >= 0) fprintf(f, "OTHER %d\n", vm->other);
    for (int i = 0; i < 8; i++) {
        char x[64], y[64], w[64], h[64];
        fmt_num(x, sizeof x, vm->view_pos[i][0]); fmt_num(y, sizeof y, vm->view_pos[i][1]);
        fmt_num(w, sizeof w, vm->view_port_set[i] ? vm->view_port[i][0] : vm->display_w);
        fmt_num(h, sizeof h, vm->view_port_set[i] ? vm->view_port[i][1] : vm->display_h);
        fprintf(f, "VIEW %d %d %s %s %s %s\n", i, vm->view_visible[i], x, y, w, h);
    }
    /* instances in id order (Rust iterates a BTreeMap) */
    int idx[MAX_INST];
    for (int i = 0; i < vm->ninst; i++) idx[i] = i;
    for (int i = 1; i < vm->ninst; i++) {
        int v = idx[i], j = i - 1;
        while (j >= 0 && vm->inst[idx[j]].id > vm->inst[v].id) { idx[j + 1] = idx[j]; j--; }
        idx[j + 1] = v;
    }
    for (int i = 0; i < vm->ninst; i++) {
        GmInst* in = &vm->inst[idx[i]];
        /* Rust dumps from a BTreeMap, so sort before printing: an unsorted
         * dump makes every run look different for no semantic reason. */
        if (in->nfields > 1) qsort(in->fields, (size_t)in->nfields, sizeof(GmField), cmp_field);
        if (in->narrays > 1) qsort(in->arrays, (size_t)in->narrays, sizeof(GmArraySlot), cmp_slot);
        fprintf(f, "INST %d %d %d\n", in->id, in->object, in->alive);
        /* Deactivation is otherwise invisible in a dump, and `with`, Step and
         * alarm dispatch all key off it. Print only the exceptional case so the
         * dump of an ordinary world is unchanged. */
        if (!in->active) fprintf(f, "ACTIVE %d 0\n", in->id);
        for (int k = 0; k < in->nfields; k++) {
            fmt_num(b1, sizeof b1, in->fields[k].value);
            fprintf(f, "FIELD %d %s %s\n", in->id, in->fields[k].name, b1);
        }
        for (int k = 0; k < in->narrays; k++) {
            fmt_num(b1, sizeof b1, in->arrays[k].value);
            fprintf(f, "ARRAY %d %s %d %s\n", in->id, in->arrays[k].name,
                    in->arrays[k].index, b1);
        }
        for (int k = 0; k < 12; k++)
            if (in->alarms[k] != -1)
                fprintf(f, "ARRAY %d alarm %d %d\n", in->id, k, in->alarms[k]);
    }
    if (vm->nglobals > 1) qsort(vm->globals, (size_t)vm->nglobals, sizeof(GmGlobal), cmp_global);
    for (int i = 0; i < vm->nglobals; i++) {
        fmt_num(b1, sizeof b1, vm->globals[i].value);
        fprintf(f, "GLOBAL %s %s\n", vm->globals[i].name, b1);
    }

    int order[GM_MAX_DRAWS];
    for (int i = 0; i < vm->ndraws; i++) order[i] = i;
    for (int i = 1; i < vm->ndraws; i++) {
        int v = order[i], j = i - 1;
        while (j >= 0) {
            GmDrawCommand* a = &vm->draws[order[j]];
            GmDrawCommand* b = &vm->draws[v];
            if (a->phase < b->phase ||
                (a->phase == b->phase && (a->depth > b->depth ||
                 (a->depth == b->depth && a->emit_order <= b->emit_order)))) break;
            order[j + 1] = order[j];
            j--;
        }
        order[j + 1] = v;
    }
    for (int oi = 0; oi < vm->ndraws; oi++) {
        GmDrawCommand* c = &vm->draws[order[oi]];
        char nums[16][512];
        fmt_num(nums[0], sizeof nums[0], c->depth);
        if (c->kind == GM_DRAW_SPRITE) {
            fmt_num(nums[1], sizeof nums[1], c->u.sprite.frame);
            fmt_num(nums[2], sizeof nums[2], c->u.sprite.x);
            fmt_num(nums[3], sizeof nums[3], c->u.sprite.y);
            fmt_num(nums[4], sizeof nums[4], c->u.sprite.scale_x);
            fmt_num(nums[5], sizeof nums[5], c->u.sprite.scale_y);
            fmt_num(nums[6], sizeof nums[6], c->u.sprite.rotation);
            fmt_num(nums[7], sizeof nums[7], c->u.sprite.alpha);
            fprintf(f, "DRAW %d SPRITE %d %d %lld %d %d %s %d %s %s %s %s %s %s %d %s %d\n",
                    oi, c->phase, c->code, (long long)c->offset, c->instance, c->view, nums[0],
                    c->u.sprite.sprite, nums[1], nums[2], nums[3], nums[4], nums[5], nums[6],
                    c->u.sprite.color, nums[7], c->u.sprite.fog);
        } else if (c->kind == GM_DRAW_TEXT) {
            fmt_num(nums[1], sizeof nums[1], c->u.text.x);
            fmt_num(nums[2], sizeof nums[2], c->u.text.y);
            fmt_num(nums[3], sizeof nums[3], c->u.text.alpha);
            char number[512];
            const char* text = gm_arg_text(vm, c->u.text.text, number, sizeof number);
            fprintf(f, "DRAW %d TEXT %d %d %lld %d %d %s %s %s %d %s %d ",
                    oi, c->phase, c->code, (long long)c->offset, c->instance, c->view, nums[0],
                    nums[1], nums[2], c->u.text.color, nums[3], c->u.text.font);
            for (const unsigned char* p = (const unsigned char*)text; *p; p++) fprintf(f, "%02x", *p);
            fputc('\n', f);
        } else if (c->kind == GM_DRAW_HEALTHBAR) {
            fmt_num(nums[1], sizeof nums[1], c->u.healthbar.x1);
            fmt_num(nums[2], sizeof nums[2], c->u.healthbar.y1);
            fmt_num(nums[3], sizeof nums[3], c->u.healthbar.x2);
            fmt_num(nums[4], sizeof nums[4], c->u.healthbar.y2);
            fmt_num(nums[5], sizeof nums[5], c->u.healthbar.amount);
            fprintf(f, "DRAW %d HEALTHBAR %d %d %lld %d %d %s %s %s %s %s %s %d %d %d\n",
                    oi, c->phase, c->code, (long long)c->offset, c->instance, c->view, nums[0],
                    nums[1], nums[2], nums[3], nums[4], nums[5], c->u.healthbar.back_col,
                    c->u.healthbar.min_col, c->u.healthbar.max_col);
        } else if (c->kind == GM_DRAW_BACKGROUND) {
            fmt_num(nums[1], sizeof nums[1], c->u.background.x);
            fmt_num(nums[2], sizeof nums[2], c->u.background.y);
            fmt_num(nums[3], sizeof nums[3], c->u.background.scale_x);
            fmt_num(nums[4], sizeof nums[4], c->u.background.scale_y);
            fmt_num(nums[5], sizeof nums[5], c->u.background.rotation);
            fmt_num(nums[6], sizeof nums[6], c->u.background.alpha);
            fprintf(f, "DRAW %d BACKGROUND %d %d %lld %d %d %s %d %s %s %s %s %s %d %s\n",
                    oi, c->phase, c->code, (long long)c->offset, c->instance, c->view, nums[0],
                    c->u.background.background, nums[1], nums[2], nums[3], nums[4], nums[5],
                    c->u.background.color, nums[6]);
        }
    }
}

/* Run one fixture through one body and write its state dump.
 * 0 = state or ERROR written, 2 = fixture/IO error, 3 = no such body here,
 * 4 = a dispatched body is absent from this binary. */
static int run_fixture(const char* in_path, const char* out_path) {
    FILE* in = fopen(in_path, "r");
    if (!in) { perror(in_path); return 2; }

    long code = -1;
    int32_t self = -1;
    /* An event sequence: real behaviour is Create -> Step -> Alarm on the same
     * scene, so a fixture may list several RUN lines. Without any, CODE is a
     * single run of `self`. */
    struct { int kind; long code; int32_t self; long ticks; } runs[128];
    int nruns = 0;
    GmVM* vm = calloc(1, sizeof(GmVM));
    if (!vm) return 2;
    vm_init(vm, 0);
    gm_objects_reset();   /* one process may run many bodies: no state may leak */

    char line[512];
    while (fgets(line, sizeof(line), in)) {
        char kind[32], name[NAME_LEN];
        long a, b, c = 1, d = 1; double v;
        if (sscanf(line, "CODE %ld", &code) == 1) continue;
        unsigned long long seed;
        if (sscanf(line, "SEED %llu", &seed) == 1) { vm->rng = (uint64_t)seed; continue; }
        if (sscanf(line, "RUN %ld %ld", &a, &b) == 2) {
            if (nruns < 128) { runs[nruns].kind = 0; runs[nruns].code = a; runs[nruns].self = (int32_t)b; nruns++; }
            continue;
        }
        if (sscanf(line, "COLLIDE %ld %ld %ld", &a, &b, &c) == 3) {
            if (nruns < 128) { runs[nruns].kind = 3; runs[nruns].code = a; runs[nruns].self = (int32_t)b; runs[nruns].ticks = c; nruns++; }
            continue;
        }
        if (sscanf(line, "TICK %ld", &a) == 1) {
            if (nruns < 128) { runs[nruns].kind = 1; runs[nruns].ticks = a; nruns++; }
            continue;
        }
        if (sscanf(line, "DRAW %ld", &a) == 1) {
            if (nruns < 128) { runs[nruns].kind = 4; runs[nruns].ticks = a; nruns++; }
            continue;
        }
        int view_index, view_visible;
        double view_x, view_y, view_w, view_h;
        if (sscanf(line, "VIEW %d %d %lf %lf %lf %lf", &view_index, &view_visible,
                   &view_x, &view_y, &view_w, &view_h) == 6) {
            if (view_index >= 0 && view_index < 8) {
                vm->view_visible[view_index] = view_visible != 0;
                vm->view_pos[view_index][0] = view_x;
                vm->view_pos[view_index][1] = view_y;
                vm->view_port[view_index][0] = view_w;
                vm->view_port[view_index][1] = view_h;
                vm->view_port_set[view_index] = 1;
            }
            continue;
        }
        if (sscanf(line, "CURRENT %ld", &a) == 1) { self = (int32_t)a; continue; }
        if (sscanf(line, "OTHER %ld", &a) == 1) { vm->other = (int32_t)a; continue; }
        if (sscanf(line, "ROOM %lf", &v) == 1) { vm->current_room = v; continue; }
        unsigned long long warp;
        if (sscanf(line, "WARP %llu", &warp) == 1) {
            vm->target_room_warp = warp;
            vm->has_room_warp = 1;
            continue;
        }
        if (sscanf(line, "%31s", kind) == 1 && strcmp(kind, "WARP") == 0) {
            if (nruns < 128) { runs[nruns].kind = 2; nruns++; }
            continue;
        }
        int nf = sscanf(line, "INST %ld %ld %ld %ld", &a, &b, &c, &d);
        if (nf >= 2) {
            /* Omitted flags default to 1. This preserves existing three-token
             * fixtures and also accepts <id> <object> with both flags implicit.
             * Ignoring a supplied third or fourth token would run a different
             * world than the VM and could still report a false `identical`. */
            GmInst* inst = vm_add(vm, (int32_t)a, (int32_t)b);
            if (!inst) { fprintf(stderr, "instance table full\n"); return 2; }
            if (nf >= 3) inst->alive = c != 0;
            if (nf >= 4) inst->active = d != 0;
            inst->spawn_seq = 1; /* ir_state_dump::build uses one for direct fixtures */
            continue;
        }
        if (sscanf(line, "FIELD %ld %47s %lf", &a, name, &v) == 3) {
            vm_set_field(vm, (int32_t)a, name, v);
            continue;
        }
        if (sscanf(line, "ARRAY %ld %47s %ld %lf", &a, name, &b, &v) == 4) {
            vm_set_array(vm, (int32_t)a, name, (int32_t)b, v);
            continue;
        }
        if (sscanf(line, "ROOMW %lf", &v) == 1) { vm->room_width = v; continue; }
        if (sscanf(line, "ROOMH %lf", &v) == 1) { vm->room_height = v; continue; }
        if (sscanf(line, "GLOBAL %47s %lf", name, &v) == 2) {
            GM_WRITE(vm, -5, name, v);
            continue;
        }
        if (sscanf(line, "%31s", kind) == 1) {
            fprintf(stderr, "unparsed line: %s\n", line);
            return 2;
        }
    }
    fclose(in);
    if (nruns == 0) {
        if (code < 0) { fprintf(stderr, "no CODE line\n"); return 2; }
        if (self < 0) self = vm->ninst ? vm->inst[0].id : 0;
        runs[0].kind = 0; runs[0].code = code; runs[0].self = self; nruns = 1;
    }
    gm_objects_register_parents();

    /* A body that hits a bad receiver must abort where the VM aborts. longjmp
     * back here keeps the generated C free of error plumbing while still
     * producing the VM's ERROR line, so the two sides stay comparable. */
    if (setjmp(gm_error_jmp) == 0) {
        gm_error_active = 1;
        int ran = 1;
        for (int i = 0; i < nruns && ran; i++) {
            if (runs[i].kind == 1) {
                for (long t = 0; t < runs[i].ticks; t++) gm_tick(vm);
            } else if (runs[i].kind == 2) {
                if (gm_room_consume_warp(vm) < 0) {
                    if (gm_missing_body_code < 0) gm_fail_msg("room transition failed");
                    ran = 0;
                }
            } else if (runs[i].kind == 3) {
                int32_t previous_other = vm->other;
                vm->other = (int32_t)runs[i].ticks;
                ran = run_code(vm, runs[i].code, runs[i].self);
                vm->other = previous_other;
            } else if (runs[i].kind == 4) {
                if (gm_draw_view(vm, (int32_t)runs[i].ticks) < 0) {
                    if (gm_missing_body_code < 0) gm_fail_msg("draw view failed");
                    ran = 0;
                }
            } else {
                ran = run_code(vm, runs[i].code, runs[i].self);
            }
        }
        gm_error_active = 0;
        if (gm_missing_body_code >= 0) {           /* 4: a dispatched body is absent */
            fprintf(stderr, "body %d has no generated function in this binary\n", gm_missing_body_code);
            return 4;
        }
        if (!ran) return 3;                        /* 3: this binary has no such body */

        FILE* out = fopen(out_path, "w");
        if (!out) { perror(out_path); return 2; }
        dump(out, vm);
        fclose(out);
        gm_strings_free(vm);
        free(vm);
        return 0;
    }

    gm_error_active = 0;
    FILE* eout = fopen(out_path, "w");
    if (eout) { fprintf(eout, "ERROR %s\n", gm_error_msg); fclose(eout); }
    gm_strings_free(vm);
    free(vm);
    return 0;
}

/* Corpus mode: one process, one engine init per body, so a whole batch costs
 * one binary start instead of one per body. Mirrors the Rust side
 * (`ir_state_dump --codes ... --outdir ...`): each line is `<code> <fixture>`
 * and the dump is named after the fixture stem, so both sides can be diffed
 * per body. */
static const char* stem_of(const char* path) {
    const char* base = strrchr(path, '/');
    return base ? base + 1 : path;
}

static int run_list(const char* list_path, const char* outdir) {
    FILE* list = fopen(list_path, "r");
    if (!list) { perror(list_path); return 2; }
    char line[1024];
    int ok = 0, err = 0, missing = 0, bad = 0;
    while (fgets(line, sizeof line, list)) {
        char fix[768];
        long code = -1;
        if (sscanf(line, "%ld %767s", &code, fix) != 2) continue;
        char outpath[1024];
        char stem[768];
        snprintf(stem, sizeof stem, "%s", stem_of(fix));
        char* dot = strrchr(stem, '.');
        if (dot) *dot = '\0';               /* fixture stem, like the Rust side */
        snprintf(outpath, sizeof outpath, "%s/%s.txt", outdir, stem);
        gm_missing_body_code = -1;
        gm_error_msg[0] = '\0';
        int rc = run_fixture(fix, outpath);
        if (rc != 0) {
            /* Batch mode has no exit code per body: leave a sentinel the
             * classifier can read instead of silently missing a file. */
            FILE* s = fopen(outpath, "w");
            if (s) {
                fprintf(s, "%s\n", rc == 2 ? "C_FIXTURE_ERROR"
                                : rc == 3 ? "C_NO_BODY"
                                : rc == 4 ? "C_MISSING_BODY" : "C_FAIL");
                fclose(s);
            }
        }
        switch (rc) {
            case 0: ok++; break;
            case 3: case 4: missing++; break;
            case 2: bad++; break;
            default: err++; break;
        }
    }
    fclose(list);
    fprintf(stderr, "bodies: ok=%d missing=%d bad=%d err=%d\n", ok, missing, bad, err);
    return bad ? 2 : 0;
}

int main(int argc, char** argv) {
    if (argc == 5 && strcmp(argv[1], "--codes") == 0 && strcmp(argv[3], "--outdir") == 0) {
        return run_list(argv[2], argv[4]);
    }
    if (argc != 3) {
        fprintf(stderr, "usage: %s <state-in> <state-out>\n", argv[0]);
        fprintf(stderr, "   or: %s --codes <list> --outdir <dir>\n", argv[0]);
        return 2;
    }
    return run_fixture(argv[1], argv[2]);
}
