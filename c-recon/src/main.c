/* State dump / differential driver.
 *
 * Reads a line-oriented state file, runs one lowered CODE function, writes the
 * resulting state in the same format. The Rust side
 * (crates/core/examples/ir_state_dump.rs) speaks the same protocol, so the two
 * implementations can be diffed byte for byte:
 *
 *     CODE    <id>
 *     CURRENT <instance id>
 *     INST    <id> <object> <alive>
 *     FIELD   <instance id> <name> <value>
 *     ARRAY   <instance id> <name> <index> <value>
 *     GLOBAL  <name> <value>
 */
#include "gml.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

void gml_0012(GmVM* vm);
void gml_0792(GmVM* vm);
int  gml_dispatch(GmVM* vm, long code);   /* generated by scripts/gen_registry.py */

static int run_code(GmVM* vm, long code, int32_t self) {
    vm->cur = self;
    if (gml_dispatch(vm, code)) return 1;
    fprintf(stderr, "no generated function for CODE %ld\n", code);
    return 0;
}

/* Shortest decimal that round-trips, like Rust's f64 Display. %.17g is exact
 * but prints 17 digits, so the same double renders as a different-looking
 * decimal than the VM's and a naive line diff reports phantom drift. */
static void fmt_num(char* buf, size_t n, double v) {
    if (v != v) { snprintf(buf, n, "NaN"); return; }
    if (v > 1.7976931348623157e308) { snprintf(buf, n, "inf"); return; }
    if (v < -1.7976931348623157e308) { snprintf(buf, n, "-inf"); return; }
    for (int prec = 15; prec < 17; prec++) {
        snprintf(buf, n, "%.*g", prec, v);
        if (strtod(buf, NULL) == v) return;
    }
    snprintf(buf, n, "%.17g", v);
}

static int cmp_field(const void* a, const void* b) {
    return strcmp(((const GmField*)a)->name, ((const GmField*)b)->name);
}
static int cmp_slot(const void* a, const void* b) {
    const GmArraySlot* x = a; const GmArraySlot* y = b;
    int c = strcmp(x->name, y->name);
    return c ? c : (x->index - y->index);
}
static int cmp_global(const void* a, const void* b) {
    return strcmp(((const GmGlobal*)a)->name, ((const GmGlobal*)b)->name);
}

static void dump(FILE* f, GmVM* vm) {
    char b1[40], b2[40];
    fmt_num(b1, sizeof b1, vm->room_width); fmt_num(b2, sizeof b2, vm->room_height);
    fprintf(f, "ROOMW %s\nROOMH %s\n", b1, b2);
    /* instances in id order (Rust iterates a BTreeMap) */
    int idx[MAX_INST];
    for (int i = 0; i < vm->ninst; i++) idx[i] = i;
    for (int i = 1; i < vm->ninst; i++) {
        int v = idx[i], j = i - 1;
        while (j >= 0 && vm->inst[idx[j]].id > vm->inst[v].id) { idx[j + 1] = idx[j]; j--; }
        idx[j + 1] = v;
    }
    for (int i = 0; i < vm->ninst; i++) {
        GmInst* in = &vm->inst[idx[i]];
        /* Rust dumps from a BTreeMap, so sort before printing: an unsorted
         * dump makes every run look different for no semantic reason. */
        if (in->nfields > 1) qsort(in->fields, (size_t)in->nfields, sizeof(GmField), cmp_field);
        if (in->narrays > 1) qsort(in->arrays, (size_t)in->narrays, sizeof(GmArraySlot), cmp_slot);
        fprintf(f, "INST %d %d %d\n", in->id, in->object, in->alive);
        for (int k = 0; k < in->nfields; k++) {
            fmt_num(b1, sizeof b1, in->fields[k].value);
            fprintf(f, "FIELD %d %s %s\n", in->id, in->fields[k].name, b1);
        }
        for (int k = 0; k < in->narrays; k++) {
            fmt_num(b1, sizeof b1, in->arrays[k].value);
            fprintf(f, "ARRAY %d %s %d %s\n", in->id, in->arrays[k].name,
                    in->arrays[k].index, b1);
        }
        for (int k = 0; k < 12; k++)
            if (in->alarms[k] != -1)
                fprintf(f, "ARRAY %d alarm %d %d\n", in->id, k, in->alarms[k]);
    }
    if (vm->nglobals > 1) qsort(vm->globals, (size_t)vm->nglobals, sizeof(GmGlobal), cmp_global);
    for (int i = 0; i < vm->nglobals; i++) {
        fmt_num(b1, sizeof b1, vm->globals[i].value);
        fprintf(f, "GLOBAL %s %s\n", vm->globals[i].name, b1);
    }
}

int main(int argc, char** argv) {
    if (argc != 3) {
        fprintf(stderr, "usage: %s <state-in> <state-out>\n", argv[0]);
        return 2;
    }
    FILE* in = fopen(argv[1], "r");
    if (!in) { perror(argv[1]); return 2; }

    long code = -1;
    int32_t self = -1;
    GmVM* vm = calloc(1, sizeof(GmVM));
    if (!vm) return 2;
    vm_init(vm, 0);

    char line[512];
    while (fgets(line, sizeof(line), in)) {
        char kind[32], name[NAME_LEN];
        long a, b; double v;
        if (sscanf(line, "CODE %ld", &code) == 1) continue;
        if (sscanf(line, "CURRENT %ld", &a) == 1) { self = (int32_t)a; continue; }
        if (sscanf(line, "INST %ld %ld", &a, &b) == 2) {
            GmInst* inst = vm_add(vm, (int32_t)a, (int32_t)b);
            if (!inst) { fprintf(stderr, "instance table full\n"); return 2; }
            continue;
        }
        if (sscanf(line, "FIELD %ld %47s %lf", &a, name, &v) == 3) {
            vm_set_field(vm, (int32_t)a, name, v);
            continue;
        }
        if (sscanf(line, "ARRAY %ld %47s %ld %lf", &a, name, &b, &v) == 4) {
            vm_set_array(vm, (int32_t)a, name, (int32_t)b, v);
            continue;
        }
        if (sscanf(line, "ROOMW %lf", &v) == 1) { vm->room_width = v; continue; }
        if (sscanf(line, "ROOMH %lf", &v) == 1) { vm->room_height = v; continue; }
        if (sscanf(line, "GLOBAL %47s %lf", name, &v) == 2) {
            GM_WRITE(vm, -5, name, v);
            continue;
        }
        if (sscanf(line, "%31s", kind) == 1) {
            fprintf(stderr, "unparsed line: %s\n", line);
            return 2;
        }
    }
    fclose(in);
    if (code < 0) { fprintf(stderr, "no CODE line\n"); return 2; }
    if (self < 0) self = vm->ninst ? vm->inst[0].id : 0;
    gm_objects_register_parents();

    if (!run_code(vm, code, self)) return 3;   /* 3: this binary has no such body */

    FILE* out = fopen(argv[2], "w");
    if (!out) { perror(argv[2]); return 2; }
    dump(out, vm);
    fclose(out);
    free(vm);
    return 0;
}
