//! Emit every ROOM placement, RoomCC binding and view default the C room loader
//! needs, using the original game.droid plus the lowered IR binding table.
//!
//!     cargo run -q -p callys-asset --example dump_rooms_c -- \
//!         assets/game.droid crates/core/src/generated/full_ir.json c-recon/gen/rooms_data.c
use callys_asset::GameDroidAsset;
use serde_json::Value;
use std::collections::BTreeMap;
use std::error::Error;
use std::fs;
use std::path::Path;

#[derive(Debug)]
struct Binding {
    instance_id: i32,
    object_id: i32,
    code_id: i32,
}

fn i64_field(v: &Value, key: &str) -> Result<i64, Box<dyn Error>> {
    v.get(key).and_then(Value::as_i64).ok_or_else(|| format!("binding missing integer {key}").into())
}

fn main() -> Result<(), Box<dyn Error>> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.len() != 3 {
        eprintln!("usage: dump_rooms_c <game.droid> <full_ir.json> <out.c>");
        std::process::exit(2);
    }
    let asset = GameDroidAsset::parse(Path::new(&args[0]))?;
    let ir_text = fs::read_to_string(&args[1])?;
    let ir: Value = serde_json::from_str(&ir_text)?;
    let mut bindings: BTreeMap<usize, Vec<Binding>> = BTreeMap::new();
    for row in ir.get("room_bindings").and_then(Value::as_array).ok_or("missing room_bindings")? {
        let room_id = i64_field(row, "room_id")? as usize;
        bindings.entry(room_id).or_default().push(Binding {
            instance_id: i64_field(row, "instance_id")? as i32,
            object_id: i64_field(row, "object_id")? as i32,
            code_id: i64_field(row, "code_id")? as i32,
        });
    }
    if asset.rooms.len() != 114 {
        return Err(format!("expected 114 rooms, got {}", asset.rooms.len()).into());
    }
    if let Some(info) = &asset.general_info {
        for (index, room) in info.room_order.iter().enumerate() {
            if index != *room {
                return Err(format!("room_order is not the identity permutation at {index}: {room}").into());
            }
        }
    }

    let mut out = String::new();
    out.push_str("/* generated by crates/asset/examples/dump_rooms_c.rs; do not hand-edit */\n");
    out.push_str(&format!("/* source_sha256 {} */\n", ir.get("source_sha256").and_then(Value::as_str).unwrap_or("missing")));
    out.push_str("#include \"gml.h\"\n\n");
    let mut total_objects = 0usize;
    let mut total_bindings = 0usize;
    for (room_id, room) in asset.rooms.iter().enumerate() {
        let room_bindings = bindings.get(&room_id).map(Vec::as_slice).unwrap_or(&[]);
        total_objects += room.objects.len();
        total_bindings += room_bindings.len();
        if room.views.len() > 8 {
            return Err(format!("room {room_id} has {} views", room.views.len()).into());
        }
        if !room.objects.is_empty() {
            out.push_str(&format!("static const GmRoomPlacement ROOM_{room_id}_OBJECTS[] = {{\n"));
            for inst in &room.objects {
                if !inst.scale_x.is_finite() || !inst.scale_y.is_finite() || !inst.rotation.is_finite() {
                    return Err(format!("room {room_id} instance {} has non-finite transform", inst.instance_id).into());
                }
                out.push_str(&format!(
                    "    {{ {}, {}, {}, {}, {}, {}, {}, {} }},\n",
                    inst.instance_id, inst.object_id, inst.creation_code_id,
                    inst.x, inst.y, inst.scale_x as f64, inst.scale_y as f64, inst.rotation as f64
                ));
            }
            out.push_str("};\n");
        }
        if !room_bindings.is_empty() {
            out.push_str(&format!("static const GmRoomBinding ROOM_{room_id}_BINDINGS[] = {{\n"));
            for binding in room_bindings {
                let matched = room.objects.iter().any(|inst| {
                    inst.instance_id == binding.instance_id
                        || (inst.object_id == binding.object_id && inst.creation_code_id == binding.code_id)
                });
                if !matched {
                    return Err(format!("room {room_id} binding {}/{}/{} has no placement",
                                       binding.instance_id, binding.object_id, binding.code_id).into());
                }
                out.push_str(&format!("    {{ {}, {}, {} }},\n",
                                      binding.instance_id, binding.object_id, binding.code_id));
            }
            out.push_str("};\n");
        }
        if !room.views.is_empty() {
            out.push_str(&format!("static const GmRoomView ROOM_{room_id}_VIEWS[] = {{\n"));
            for view in &room.views {
                out.push_str(&format!("    {{ {}, {}, {}, {}, {} }},\n",
                                      view.visible as i32, view.xview, view.yview, view.wport, view.hport));
            }
            out.push_str("};\n");
        }
        let objects_ptr = if room.objects.is_empty() { "NULL".into() } else { format!("ROOM_{room_id}_OBJECTS") };
        let bindings_ptr = if room_bindings.is_empty() { "NULL".into() } else { format!("ROOM_{room_id}_BINDINGS") };
        let views_ptr = if room.views.is_empty() { "NULL".into() } else { format!("ROOM_{room_id}_VIEWS") };
        out.push_str(&format!(
            "static const GmRoom ROOM_{room_id}_DATA = {{ {}, {}, {}, {}, {}, {}, {}, {}, {} }}; /* {} */\n\n",
            room.width, room.height, room.speed,
            objects_ptr, room.objects.len(), bindings_ptr, room_bindings.len(), views_ptr, room.views.len(), room.name
        ));
    }
    out.push_str("const GmRoom GM_ROOMS[] = {\n");
    for room_id in 0..asset.rooms.len() {
        out.push_str(&format!("    ROOM_{room_id}_DATA,\n"));
    }
    out.push_str("};\n");
    out.push_str(&format!("const int GM_ROOM_COUNT = {};\n", asset.rooms.len()));
    fs::write(&args[2], out)?;
    println!("{} rooms / {} placements / {} RoomCC bindings -> {}",
             asset.rooms.len(), total_objects, total_bindings, args[2]);
    Ok(())
}
