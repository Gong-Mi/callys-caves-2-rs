/// What one argument push sequence evaluates to, symbolically.
#[derive(Debug, Clone, Copy, PartialEq)]
enum Val {
    Num(f64),
    Pos { is_y: bool, delta: f64 },
    SelfFrame,
}

/// Decode the nine `draw_sprite_ext` arguments the instructions immediately
/// before the call at `off` push. Pushes go in reverse argument order (alpha
/// first, sprite last), which is exactly how `code_vm::execute` pops them.
fn decode_draw_args(code: &Code, off: usize) -> [Val; 9] {
    let k = code
        .instructions
        .iter()
        .position(|i| i.code_offset == off)
        .unwrap_or_else(|| panic!("CODE 374 has no instruction at code_offset {off}"));
    match &code.instructions[k].op {
        Op::Call { name, argc } => {
            assert_eq!(name, "draw_sprite_ext", "code_offset {off} is not a draw");
            assert_eq!(*argc, 9, "code_offset {off}: draw_sprite_ext arity");
        }
        other => panic!("code_offset {off} is {other:?}, not a draw_sprite_ext call"),
    }
    let mut start = k;
    while start > 0 {
        let push = matches!(
            code.instructions[start - 1].op,
            Op::Constant { .. }
                | Op::Load { .. }
                | Op::String { .. }
                | Op::Add
                | Op::Sub
                | Op::Mul
                | Op::Div
                | Op::Cast { .. }
                | Op::Dup
                | Op::Not
                | Op::And
        );
        if !push {
            break;
        }
        start -= 1;
    }
    let mut st: Vec<Val> = Vec::new();
    for i in &code.instructions[start..k] {
        match &i.op {
            Op::Constant { value } => st.push(Val::Num(*value)),
            Op::Load { name, selector, .. } => st.push(match (name.as_str(), *selector) {
                ("x", 0) => Val::Pos {
                    is_y: false,
                    delta: 0.0,
                },
                ("y", 0) => Val::Pos {
                    is_y: true,
                    delta: 0.0,
                },
                ("frame", -1) => Val::SelfFrame,
                other => panic!(
                    "unexpected operand load {other:?} in CODE 374's draw at code_offset {off}"
                ),
            }),
            Op::Cast { to } => assert!(
                matches!(*to, 0 | 4 | 5),
                "code_offset {off}: unexpected cast to {to}"
            ),
            Op::Add | Op::Sub => {
                let rhs = st.pop().expect("operand");
                let lhs = st.pop().expect("operand");
                let add = matches!(i.op, Op::Add);
                st.push(match (lhs, rhs, add) {
                    (Val::Num(a), Val::Num(b), true) => Val::Num(a + b),
                    (Val::Num(a), Val::Num(b), false) => Val::Num(a - b),
                    (Val::Pos { is_y, delta }, Val::Num(b), true) => Val::Pos {
                        is_y,
                        delta: delta + b,
                    },
                    (Val::Pos { is_y, delta }, Val::Num(b), false) => Val::Pos {
                        is_y,
                        delta: delta - b,
                    },
                    (l, r, _) => panic!("code_offset {off}: unsupported operand pair {l:?} {r:?}"),
                });
            }
            other => panic!("code_offset {off}: unexpected operand instruction {other:?}"),
        }
    }
    assert_eq!(
        st.len(),
        9,
        "code_offset {off}: the argument run pushes exactly 9 values"
    );
    let mut out = [Val::Num(0.0); 9];
    for (n, v) in st.iter().rev().enumerate() {
        out[n] = *v;
    }
    out
}

