#[test]
fn trex_pose_beats_swap_sprite_and_charge_behind_the_room_gate() {
    let b = bundle();
    // CODE 158 = obj_trex Alarm_3 and CODE 159 = obj_trex Alarm_2:
    //   if (room == rm_ending) { }
    //   else if (room != rm_ending) {
    //       sprite_index = spr_mallatohn / spr_bearslash;   (IR 56 / 54)
    //       alarm[3] = 90 / hspeed = 3, alarm[2] = 90 / hspeed = -3;
    //   }
    // The trex carries two pose/patrol timers that hand the charge back and forth.

    // CODE 158 outside the ending room.
    let mut s = scene(&b);
    let p = player(&mut s, &b, 500.0, 200.0);
    park(&mut s, p);
    let t = s.create(&b, TREX, 300.0, 200.0).expect("obj_trex");
    {
        let i = s.instances.get_mut(&t).unwrap();
        i.fields.insert("sprite_index".into(), -7.0); // sentinel
        i.fields.insert("hspeed".into(), 0.0);
    }
    let before = snapshot(&s, t);
    let f_before = fields_sorted(&s, t);
    s.dispatch(&b, t, 2, 3).expect("Alarm_3");
    assert_eq!(
        s.instances[&t].fields["sprite_index"], SPR_MALLATOHN,
        "CODE 158 swaps to spr_mallatohn (56)"
    );
    assert_eq!(
        s.instances[&t].fields["hspeed"], 3.0,
        "CODE 158 drives the charge to the right at 3"
    );
    expect_only(
        &f_before,
        &fields_sorted(&s, t),
        &[("sprite_index", SPR_MALLATOHN), ("hspeed", 3.0)],
        "CODE 158",
    );
    assert_only_slot(&s, t, &before, 3, 90, "CODE 158");

    // CODE 159 outside the ending room.
    let mut s = scene(&b);
    let p = player(&mut s, &b, 500.0, 200.0);
    park(&mut s, p);
    let t = s.create(&b, TREX, 300.0, 200.0).expect("obj_trex");
    {
        let i = s.instances.get_mut(&t).unwrap();
        i.fields.insert("sprite_index".into(), -7.0);
        i.fields.insert("hspeed".into(), 0.0);
    }
    let before = snapshot(&s, t);
    let f_before = fields_sorted(&s, t);
    s.dispatch(&b, t, 2, 2).expect("Alarm_2");
    assert_eq!(
        s.instances[&t].fields["sprite_index"], SPR_BEARS_LAISH,
        "CODE 159 swaps to spr_bearslash (54)"
    );
    assert_eq!(
        s.instances[&t].fields["hspeed"], -3.0,
        "CODE 159 drives the charge to the left at 3"
    );
    expect_only(
        &f_before,
        &fields_sorted(&s, t),
        &[("sprite_index", SPR_BEARS_LAISH), ("hspeed", -3.0)],
        "CODE 159",
    );
    assert_only_slot(&s, t, &before, 2, 90, "CODE 159");

    // Both beats are inert in rm_ending: the empty `if` branch wins, so no sprite,
    // no velocity and no timer write.
    let mut s = scene(&b);
    let p = player(&mut s, &b, 500.0, 200.0);
    park(&mut s, p);
    let t = s.create(&b, TREX, 300.0, 200.0).expect("obj_trex");
    {
        let i = s.instances.get_mut(&t).unwrap();
        i.fields.insert("sprite_index".into(), -7.0);
        i.fields.insert("hspeed".into(), 0.0);
    }
    s.current_room = RM_ENDING;
    let before = snapshot(&s, t);
    let f_before = fields_sorted(&s, t);
    s.dispatch(&b, t, 2, 3).expect("Alarm_3 in rm_ending");
    s.dispatch(&b, t, 2, 2).expect("Alarm_2 in rm_ending");
    assert_eq!(
        s.instances[&t].fields["sprite_index"], -7.0,
        "both pose beats are gated on `room != rm_ending`"
    );
    assert_eq!(
        s.instances[&t].fields["hspeed"], 0.0,
        "and write no velocity"
    );
    expect_only(&f_before, &fields_sorted(&s, t), &[], "CODE 158/159 gated");
    assert_eq!(
        snapshot(&s, t),
        before,
        "and arm nothing in the ending room"
    );
    assert!(s.instances[&t].alive);

    // Scheduler side of CODE 158: the body's own re-arm is a real clock. The
    // Create body armed slot 3 to 100 and slot 2 to 80, so the fixture re-arms
    // slot 3 to 90 (the value the body itself writes) and then counts it down;
    // the pose beat must land on the 90th tick and re-arm to 90, while slot 2's
    // own 80-tick patrol beat fires before it (it swaps the sprite to 54) - so the
    // sprite alone cannot date the fire and the alarm readback does.
    let mut s = scene(&b);
    let p = player(&mut s, &b, 500.0, 200.0);
    park(&mut s, p);
    let t = s.create(&b, TREX, 300.0, 200.0).expect("obj_trex");
    s.instances
        .get_mut(&t)
        .unwrap()
        .fields
        .insert("hspeed".into(), 0.0);
    s.dispatch(&b, t, 2, 3)
        .expect("Alarm_3 arms its own 90-tick clock");
    assert_eq!(
        s.instances[&t].alarms[3], 90,
        "fixture: CODE 158's own re-arm value"
    );
    for step in 1..90 {
        pin(&mut s, p, 500.0, 200.0);
        pin(&mut s, t, 300.0, 200.0);
        s.tick(&b).unwrap();
        assert_eq!(
            s.instances[&t].alarms[3],
            90 - step,
            "CODE 158's own clock counts down one per tick"
        );
        assert!(s.instances[&t].alive, "the boss survives its pose beats");
    }
    assert_eq!(
        s.instances[&t].alarms[3], 1,
        "one tick left before CODE 158 self-fires"
    );
    pin(&mut s, p, 500.0, 200.0);
    pin(&mut s, t, 300.0, 200.0);
    s.tick(&b).unwrap();
    assert_eq!(
        s.instances[&t].alarms[3], 90,
        "CODE 158 self-fired and re-armed to 90"
    );
    assert_eq!(
        s.instances[&t].fields["sprite_index"], SPR_MALLATOHN,
        "and wore spr_mallatohn (56 - not slot 2's spr_bearslash) at the end"
    );
}

#[test]
fn trex_draw_washes_white_while_flashing_and_clears_the_flag() {
    let b = bundle();
    // CODE 162 = obj_trex Draw_0: with flashing == 1 it wraps draw_self() in
    // d3d_set_fog(true, c_white, 0, 0) and resets flashing to 0; with flashing == 0
    // it draws the plain sprite.
    let mut s = scene(&b);
    let p = player(&mut s, &b, 500.0, 200.0);
    park(&mut s, p);
    let t = s.create(&b, TREX, 300.0, 200.0).expect("obj_trex");
    let sprite = s.instances[&t].fields["sprite_index"];
    assert_eq!(
        sprite, SPR_MALLATOHN,
        "fixture: the trex Create keeps spr_mallatohn"
    );
    s.instances
        .get_mut(&t)
        .unwrap()
        .fields
        .insert("flashing".into(), 1.0);
    s.draws.clear();
    s.dispatch(&b, t, 8, 0).expect("Draw_0 flashing");
    assert_eq!(
        s.draws.len(),
        1,
        "CODE 162 draws the boss once while flashing"
    );
    let d = &s.draws[0];
    assert_eq!(d.code, 162, "attributed to CODE 162");
    assert!(d.fog, "the draw is wrapped in d3d_set_fog(true, ...)");
    assert_eq!(d.color, C_WHITE, "fog colour c_white (16777215)");
    assert_eq!(
        d.sprite, sprite as i32,
        "draw_self of the boss's own sprite"
    );
    assert_eq!(
        s.instances[&t].fields["flashing"], 0.0,
        "CODE 162 resets flashing to 0 at the end of the same Draw"
    );
    assert!(!s.fog_enabled, "the body switches the fog back off");

    // Next frame: flashing is 0, so the plain blend is used.
    s.instances
        .get_mut(&t)
        .unwrap()
        .fields
        .insert("image_blend".into(), 255.0);
    s.draws.clear();
    s.dispatch(&b, t, 8, 0).expect("Draw_0 plain");
    assert_eq!(s.draws.len(), 1);
    let d = &s.draws[0];
    assert_eq!(d.code, 162);
    assert!(!d.fog, "no fog on the non-flashing path");
    assert_eq!(
        d.color, 255,
        "the plain path passes image_blend straight through"
    );
    assert_eq!(
        s.instances[&t].fields["image_blend"], 255.0,
        "flashing == 0 leaves image_blend untouched"
    );
    assert_eq!(
        s.instances[&t].fields["flashing"], 0.0,
        "and the flag stays down"
    );
}
