//! WL41 — id-level body semantics for the player's own alarm ladder and the
//! whole obj_trex family.
//!
//! obj_player (object 0), the seven cited bodies that carried no id-level test:
//!   Alarm_2 CODE 9, Alarm_3 CODE 8, Alarm_4 CODE 7, Alarm_5 CODE 6,
//!   Alarm_7 CODE 4, Alarm_8 CODE 3, Alarm_10 CODE 2.
//! obj_trex (object 25), all six remaining bodies:
//!   Destroy_0 CODE 155, Alarm_6 CODE 156, Alarm_5 CODE 157, Alarm_3 CODE 158,
//!   Alarm_2 CODE 159, Draw_0 CODE 162.
//!
//! REWRITE-SIDE IR REGRESSION SEMANTICS. Every asserted value was read out of the
//! recovered GML body (`cally-recovered-gml/restored-source/gml/NNNN__*.gml`) and
//! cross-checked against the constants in the generated bytecode IR
//! (`crates/core/src/generated/full_ir.json`) on this host. This is NOT a proof of
//! equivalence with the original GameMaker runner. The shared suites
//! (`original_player_create`, `boss1_trex_kill_chain_ir`, `entity_flashing_ir`)
//! already execute some of these bodies end to end; this file adds the per-body
//! id naming and the explicit assertion of what each body changes on its own.
//!
//! Constants are the IR constants of the body under test, not guessed names:
//!   spr_player 29 (CODE 4/9), spr_bearslash 54 (CODE 159), spr_mallatohn 56
//!   (CODE 158), mus_bosssongending 50 (CODE 155), c_white 16777215 (CODE 162),
//!   rm_ending 110 (CODE 158/159). obj_lloyd 154, obj_bosspuff 190 and obj_damage
//!   104 are CODE 155's / CODE 156's own instance_create arguments.
//!
//! Fixture discipline (shared with `enemy_ladders_ii_ir`, `mines_slime_ir`,
//! `boss_family_id_bodies_ir`):
//!  * every body is driven by a DIRECT `dispatch` first, so no same-tick Step can
//!    overwrite the value under assertion; each body that arms its own alarm is
//!    then re-run through the real scheduler;
//!  * the scheduler only visits alive AND active instances, so the player stays
//!    active in its own alarm tests and is parked in the trex tests;
//!  * the player and the actor are pinned to fixed coordinates every frame of a
//!    timer run — both Steps rewrite velocities and positions each tick;
//!  * `global.pwr` is a room-configuration global seeded by the original's room
//!    initializer, never an engine-recomputed field, so the fixture sets it;
//!  * no enemy exists in these scenes, so the player Step's enemy-collision
//!    branches — the only nested writers of `sliding1`/`sliding2` and of
//!    alarm slots 4/7/8 — never run, which is what makes the hand-armed slots
//!    below readable.

