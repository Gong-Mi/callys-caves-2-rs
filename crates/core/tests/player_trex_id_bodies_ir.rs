#[test]
fn trex_destroy_stops_the_audio_leaves_lloyd_and_a_puff() {
    let b = bundle();
    // CODE 155 = obj_trex Destroy_0:
    //   audio_stop_all();
    //   audio_play_sound(mus_bosssongending, 0, false);   (IR sound constant 50)
    //   instance_create(962, 352, obj_lloyd);             (IR object constant 154)
    //   instance_create(x, y - 32, obj_bosspuff);         (IR object constant 190)
    let mut s = scene(&b);
    let p = player(&mut s, &b, 500.0, 200.0);
    park(&mut s, p);
    let t = s.create(&b, TREX, 300.0, 200.0).expect("obj_trex");
    assert_eq!(
        s.instances[&t].fields["hptrex"], TREX_HP_PWR1,
        "fixture: the trex Create body seeds the pwr-1 HP"
    );

    // Music is already running: audio_stop_all() must tear the live voice down.
    s.call_audio_play(29.0, 0.0, true);
    assert!(
        s.audio_voices
            .iter()
            .any(|v| v.sound == 29.0 && v.looping && !v.stopped),
        "fixture: a looping music voice is live"
    );
    s.audio.clear();
    let _ = s.take_stop_commands();

    s.destroy(&b, t).expect("destroy runs the Destroy body");
    assert!(
        !s.instances[&t].alive,
        "the Destroy event ends with the boss gone"
    );
    assert!(
        s.audio_voices.iter().any(|v| v.sound == 29.0 && v.stopped),
        "audio_stop_all() stops the live music voice"
    );
    assert!(
        s.take_stop_commands().contains(&29.0),
        "and queues the host-side stop for the music it killed"
    );
    assert_eq!(s.audio.len(), 1, "the body queues exactly one sound");
    let cmd = &s.audio[0];
    assert_eq!(
        cmd.sound, SND_BOSSSONGENDING,
        "mus_bosssongending is SOND 50"
    );
    assert_eq!(cmd.priority, 0.0, "played at priority 0");
    assert!(!cmd.looping, "played with loop = false");
    assert_eq!(cmd.code, 155, "the AudioCommand is attributed to CODE 155");

    let lloyds = lives(&s, LLOYD);
    assert_eq!(lloyds.len(), 1, "CODE 155 leaves exactly one obj_lloyd");
    let li = &s.instances[&lloyds[0]];
    assert_eq!(
        (li.fields["x"], li.fields["y"]),
        (LLOYD_X, LLOYD_Y),
        "instance_create(962, 352, obj_lloyd) at the ending spot"
    );
    let puffs = lives(&s, BOSSPUFF);
    assert_eq!(puffs.len(), 1, "and exactly one obj_bosspuff");
    let pi = &s.instances[&puffs[0]];
    assert_eq!(
        (pi.fields["x"], pi.fields["y"]),
        (300.0, 200.0 + PUFF_DY),
        "instance_create(x, y - 32, obj_bosspuff) relative to the boss"
    );
}

#[test]
fn trex_poison_slot_bites_and_re_arms_itself() {
    let b = bundle();
    // CODE 156 = obj_trex Alarm_6: poisoned = 1, hptrex -= 0.25, one obj_damage
    // (104) carrying damage = 0.25, then alarm[6] = 30. Nothing else in the corpus
    // arms slot 6 on the trex, so the body is its own clock.
    let mut s = scene(&b);
    let p = player(&mut s, &b, 500.0, 200.0);
    park(&mut s, p);
    let t = s.create(&b, TREX, 300.0, 200.0).expect("obj_trex");
    let hp0 = s.instances[&t].fields["hptrex"];
    assert_eq!(hp0, TREX_HP_PWR1, "fixture: pwr 1 seeds the Create's HP");
    let before = snapshot(&s, t);
    s.dispatch(&b, t, 2, 6).expect("Alarm_6");
    assert_eq!(
        s.instances[&t].fields["poisoned"], 1.0,
        "CODE 156 raises the poison flag"
    );
    assert_eq!(
        hp0 - s.instances[&t].fields["hptrex"],
        0.25,
        "CODE 156 takes a quarter heart off hptrex"
    );
    assert_only_slot(&s, t, &before, 6, 30, "CODE 156");
    let dmg = lives(&s, DAMAGE);
    assert_eq!(dmg.len(), 1, "one obj_damage number");
    let di = &s.instances[&dmg[0]];
    assert_eq!(
        di.fields["damage"], 0.25,
        "the number carries damage = 0.25"
    );
    assert_eq!(
        (di.fields["x"], di.fields["y"]),
        (300.0, 200.0),
        "created at the boss's own coordinates"
    );

    // Through the real scheduler: the armed 30-tick timer fires the same body
    // again and re-arms itself.
    for _ in 0..30 {
        pin(&mut s, p, 500.0, 200.0);
        pin(&mut s, t, 300.0, 200.0);
        s.tick(&b).unwrap();
    }
    assert_eq!(
        hp0 - s.instances[&t].fields["hptrex"],
        0.5,
        "CODE 156 self-fired once on its own 30-tick alarm"
    );
    assert_eq!(
        s.instances[&t].alarms[6], 30,
        "and re-armed its own slot to 30"
    );
    assert_eq!(
        created(&s, DAMAGE),
        2,
        "two damage numbers were created in total"
    );
}

