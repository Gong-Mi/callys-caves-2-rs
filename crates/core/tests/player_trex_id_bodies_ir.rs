#[test]
fn player_alarm_10_advances_the_play_clock_and_re_arms_itself() {
    let b = bundle();
    // CODE 2 = obj_player Alarm_10:
    //   global.timeplayed += 1;
    //   alarm[10] = 30;
    // The body is its own clock: nothing else in the corpus writes slot 10 on the
    // player (the Step never touches it), and Create seeds the first 30.
    let mut s = scene(&b);
    let p = player(&mut s, &b, 500.0, 200.0);
    assert_eq!(s.globals["timeplayed"], 0.0, "fixture: fresh start clock");
    s.instances.get_mut(&p).unwrap().alarms[10] = 7; // sentinel: the body owns this slot
    let before = snapshot(&s, p);
    let g_before = globals_sorted(&s);
    s.dispatch(&b, p, 2, 10).expect("Alarm_10");
    let after = globals_sorted(&s);
    expect_only(&g_before, &after, &[("timeplayed", 1.0)], "CODE 2");
    assert_eq!(
        s.globals["timeplayed"], 1.0,
        "CODE 2 adds exactly one to global.timeplayed"
    );
    assert_only_slot(&s, p, &before, 10, 30, "CODE 2");

    // Second dispatch on the real scheduler: Create armed slot 10 to 30, so the
    // body must fire on the 30th tick and re-arm to 30, exactly like the boss
    // poison slots.
    let mut s = scene(&b);
    let p = player(&mut s, &b, 500.0, 200.0);
    assert_eq!(
        s.instances[&p].alarms[10], 30,
        "fixture: Create arms the clock to 30"
    );
    for t in 1..30 {
        pin(&mut s, p, 500.0, 200.0);
        s.tick(&b).unwrap();
        assert_eq!(
            s.instances[&p].alarms[10],
            30 - t,
            "CODE 2: still counting down at tick {t}"
        );
        assert_eq!(
            s.globals["timeplayed"], 0.0,
            "CODE 2: nothing yet at tick {t}"
        );
    }
    pin(&mut s, p, 500.0, 200.0);
    s.tick(&b).unwrap();
    assert_eq!(
        s.globals["timeplayed"], 1.0,
        "CODE 2 self-fired on the 30th tick"
    );
    assert_eq!(
        s.instances[&p].alarms[10], 30,
        "CODE 2 re-armed its own slot to 30"
    );
}

